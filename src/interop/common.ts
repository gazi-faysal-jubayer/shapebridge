import { resolve, type Doc, type Feature, type PlaneName } from "../model/doc";
import { orderParams, isLiteral } from "../model/params";
import { FRAMES } from "../model/geometry";

/** Shared prologue for generators: validates the doc and orders params by dependency. */
export function prepare(doc: Doc) {
  const { env, num, features } = resolve(doc);
  const params = orderParams(doc.params).map((p) => ({ ...p, literal: isLiteral(p.expr) }));
  return { env, num, features, params };
}

export const header = (doc: Doc, comment: string) =>
  `${comment} ${doc.name}: generated by ShapeBridge (https://github.com/gazi-faysal-jubayer/shapebridge)\n` +
  `${comment} Units: mm. Edit the parameters below; geometry updates from them.\n`;

/** Unit normal of each base plane, as used for mirrors and sketch frames. */
export const normalOf = (p: PlaneName) => FRAMES[p].n;

/** Features later ones can copy (patterns), keyed by id. */
export const isTool = (f: Feature): f is Extract<Feature, { kind: "extrude" | "revolve" | "hole" }> =>
  f.kind === "extrude" || f.kind === "revolve" || f.kind === "hole";

/** `expr` scaled by a unit-vector component: 0, expr, or -(expr). */
export const scaled = (k: number, expr: string) => (k === 0 ? "0" : k === 1 ? `(${expr})` : `-(${expr})`);
